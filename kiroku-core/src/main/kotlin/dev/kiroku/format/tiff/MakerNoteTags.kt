    /** Leica MakerNotes reuse Panasonic tags for the Panasonic-built (RWL) models. */
    private val leica = panasonic

    fun forVendor(vendor: String): Map<Int, String> = when (vendor) {
        "Canon" -> canon
        "Nikon" -> nikon
        "Olympus" -> olympus
        "Sony" -> sony
        "Panasonic" -> panasonic
        "Leica" -> leica
        "FujiFilm" -> fujifilm
        "Pentax" -> pentax
        "Samsung" -> samsung
        "Apple" -> apple
        "Casio" -> casio
        "Sigma" -> sigma
        else -> emptyMap()
    }

    /** Vendor tags whose value is an offset to (or the bytes of) a sub-IFD, even when not typed as IFD. */
    fun subIfdTags(vendor: String): Set<Int> = when (vendor) {
        "Olympus" -> setOf(0x2010, 0x2020, 0x2030, 0x2031, 0x2040, 0x2050, 0x3000)
        "Nikon" -> setOf(0x0011)
        "Samsung" -> setOf(0x0035)
        else -> emptySet()
    }

    fun forSubIfd(vendor: String, subName: String): Map<Int, String> = when {
        vendor == "Olympus" && subName == "Equipment" -> olympusEquipment
        vendor == "Olympus" && subName == "CameraSettings" -> olympusCameraSettings
        subName.endsWith("PreviewIFD") || subName == "PreviewIFD" -> TiffTags.main
        else -> emptyMap()
    }
