    fun nameFor(table: TagTable, tag: Int): String? = when (table) {
        TagTable.MAIN -> main[tag]
        TagTable.GPS -> gps[tag]
        TagTable.INTEROP -> interop[tag]
        TagTable.PANASONIC_RAW -> panasonicRaw[tag] ?: if (tag in PANASONIC_STANDARD) main[tag] else null
        TagTable.MAKERNOTE -> null
    }

    fun unknownName(tag: Int): String = "0x%04X".format(tag)

    /** Standard TIFF tags that keep their meaning in PanasonicRaw IFD0 (the others in 0x0100-0x01FF are private). */
    private val PANASONIC_STANDARD = setOf(0x010F, 0x0110, 0x0111, 0x0112, 0x0116, 0x0117, 0x02BC, 0x83BB, 0x8769, 0x8825, 0x8773)
}

