#!/usr/bin/env bash
# Regenerates the synthetic fixtures in fixtures/media/generated using ffmpeg and ExifTool.
# Synthetic media is generated (CC0); device, GPS and date tags are written explicitly so that
# expected values are known. Run scripts/record-expected.sh afterwards to refresh the
# independently-observed (ExifTool/ffprobe) expectations in fixtures/manifest.json.
#
# Requirements: ffmpeg (libx264, libx265, libvpx-vp9, libwebp, libopus), ExifTool (EXIFTOOL env or PATH).
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
OUT="$ROOT/fixtures/media/generated"
EXIFTOOL="${EXIFTOOL:-$(command -v exiftool || echo "$ROOT/.tools/exiftool-dist/exiftool")}"
FF=(ffmpeg -v error -y -hide_banner)
ET=("$EXIFTOOL" -q -overwrite_original)
TMP="$(mktemp -d)"
trap 'rm -rf "$TMP"' EXIT
mkdir -p "$OUT"
cd "$OUT"

src_video=(-f lavfi -i "testsrc2=size=320x240:rate=30:duration=1")
src_audio=(-f lavfi -i "sine=frequency=440:duration=1:sample_rate=48000")
bitexact=(-fflags +bitexact -flags:v +bitexact -flags:a +bitexact)

# 1. JPEG with full EXIF (camera, lens, exposure, GPS, orientation 6, time offset + subseconds), XMP, IPTC.
"${FF[@]}" -f lavfi -i "testsrc2=size=640x480" -frames:v 1 -q:v 4 "$TMP/base.jpg"
cp "$TMP/base.jpg" jpeg_full_exif.jpg
"${ET[@]}" -n \
  -EXIF:Make="Kiroku Test Optics" -EXIF:Model="KT-1000 Mark II" -EXIF:Software="KT Firmware 1.2.3" \
  -EXIF:Orientation=6 -EXIF:DateTimeOriginal="2023:06:17 14:32:10" -EXIF:SubSecTimeOriginal=123 \
  -EXIF:OffsetTimeOriginal="+02:00" -EXIF:CreateDate="2023:06:17 14:32:10" -EXIF:ModifyDate="2023:06:18 09:00:00" \
  -EXIF:OffsetTime="+02:00" -EXIF:ISO=400 -EXIF:FNumber=2.8 -EXIF:ExposureTime=0.004 -EXIF:FocalLength=35 \
  -EXIF:FocalLengthIn35mmFormat=52 -EXIF:ExposureCompensation=-0.7 -EXIF:MeteringMode=5 -EXIF:ExposureProgram=3 \
  -EXIF:Flash=16 -EXIF:WhiteBalance=0 -EXIF:LensMake="Kiroku" -EXIF:LensModel="KT 35mm F1.8" \
  -EXIF:LensSerialNumber="LS-0042" -EXIF:SerialNumber="BODY-12345" -EXIF:ColorSpace=1 \
  -EXIF:GPSLatitude=48.858222 -EXIF:GPSLatitudeRef=N -EXIF:GPSLongitude=2.2945 -EXIF:GPSLongitudeRef=E \
  -EXIF:GPSAltitude=35.5 -EXIF:GPSAltitudeRef=0 -EXIF:GPSImgDirection=123.4 -EXIF:GPSImgDirectionRef=T \
  -EXIF:GPSDateStamp="2023:06:17" -EXIF:GPSTimeStamp="12:32:09" -EXIF:GPSMapDatum="WGS-84" \
  -EXIF:Artist="Test Photographer" -EXIF:Copyright="CC0 Kiroku fixtures" \
  -XMP-dc:Title="Eiffel Test" -XMP-dc:Subject="tower" -XMP-dc:Subject="paris" -XMP-xmp:Rating=4 \
  -IPTC:Keywords="tower" -IPTC:Keywords="travel" -IPTC:ObjectName="Eiffel Test" -IPTC:Credit="Kiroku" \
  jpeg_full_exif.jpg

# 2. JPEG with timezone-free EXIF and conflicting XMP camera model (conflict preservation).
cp "$TMP/base.jpg" jpeg_no_timezone.jpg
"${ET[@]}" -EXIF:Make="Kiroku" -EXIF:Model="KT-200" -EXIF:DateTimeOriginal="2021:12:24 18:05:00" \
  -XMP-tiff:Model="KT-200 (edited)" -XMP-exif:DateTimeOriginal="2021-12-24T18:05:00" jpeg_no_timezone.jpg

# 3. PNG with XMP, tEXt and eXIf.
"${FF[@]}" -f lavfi -i "testsrc2=size=200x100" -frames:v 1 "$TMP/base.png"
cp "$TMP/base.png" png_xmp_text.png
"${ET[@]}" -PNG:Title="PNG Title" -PNG:Author="PNG Author" -PNG:Comment="Generated by Kiroku" \
  -XMP-dc:Description="PNG with XMP" -XMP-dc:Subject="png" -EXIF:Make="Kiroku" -EXIF:Model="PNG-Cam" \
  -EXIF:DateTimeOriginal="2022:01:02 03:04:05" png_xmp_text.png

# 4. BMP without camera fields.
"${FF[@]}" -f lavfi -i "testsrc2=size=64x48" -frames:v 1 -pix_fmt bgr24 bmp_plain.bmp

# 5. Animated GIF (10 frames, infinite loop) and a single-frame GIF.
"${FF[@]}" -f lavfi -i "testsrc2=size=80x60:rate=10:duration=1" -loop 0 gif_animated.gif
"${FF[@]}" -f lavfi -i "testsrc2=size=80x60" -frames:v 1 gif_static.gif

# 6. WebP: lossy still with EXIF/XMP, and animated.
"${FF[@]}" -f lavfi -i "testsrc2=size=160x120" -frames:v 1 -c:v libwebp -quality 70 webp_exif_xmp.webp
"${ET[@]}" -EXIF:Make="Kiroku" -EXIF:Model="WebP-Cam" -EXIF:DateTimeOriginal="2020:02:29 12:00:00" \
  -EXIF:OffsetTimeOriginal="-05:00" -XMP-dc:Title="WebP Title" webp_exif_xmp.webp
"${FF[@]}" -f lavfi -i "testsrc2=size=96x64:rate=5:duration=1" -c:v libwebp_anim -loop 3 webp_animated.webp

# 7. TIFF (single page) with EXIF.
"${FF[@]}" -f lavfi -i "testsrc2=size=120x90" -frames:v 1 -pix_fmt rgb24 tiff_basic.tif
"${ET[@]}" -EXIF:Make="Kiroku" -EXIF:Model="Scanner-T" -EXIF:Orientation#=8 tiff_basic.tif

# 8. iPhone-style MOV: HEVC + AAC, Apple mdta keys (make/model/GPS/creation date/software), portrait (90° CW).
"${FF[@]}" "${src_video[@]}" "${src_audio[@]}" -c:v libx265 -x265-params log-level=error -tag:v hvc1 -c:a aac \
  -movflags use_metadata_tags \
  -metadata com.apple.quicktime.make=Apple -metadata "com.apple.quicktime.model=iPhone 15 Pro" \
  -metadata "com.apple.quicktime.location.ISO6709=+35.6895+139.6917+040.000/" \
  -metadata "com.apple.quicktime.creationdate=2024-05-03T10:15:30+0900" \
  -metadata com.apple.quicktime.software=17.4.1 -metadata creation_time=2024-05-03T01:15:31Z "$TMP/phone.mov"
"${FF[@]}" -display_rotation -90 -i "$TMP/phone.mov" -c copy -map_metadata 0 -movflags use_metadata_tags video_iphone_style.mov

# 9. Android-style MP4: H.264 + AAC, udta ©xyz location, make/model.
"${FF[@]}" "${src_video[@]}" "${src_audio[@]}" -c:v libx264 -preset ultrafast -c:a aac \
  -metadata location=+37.4220-122.0841/ -metadata make=Google -metadata "model=Pixel 8" \
  -metadata creation_time=2023-09-01T08:00:00Z video_android_style.mp4

# 10. Edited/transcoded MP4 with stripped metadata: camera must be null.
"${FF[@]}" -i video_android_style.mp4 -map_metadata -1 -c:v libx264 -preset ultrafast -c:a aac "${bitexact[@]}" video_stripped.mp4

# 11. AVI (MPEG-4 Part 2 + PCM) with RIFF INFO.
"${FF[@]}" "${src_video[@]}" "${src_audio[@]}" -c:v mpeg4 -c:a pcm_s16le -metadata title="AVI Title" -metadata artist="AVI Artist" video_basic.avi

# 12. WebM (VP9 + Opus).
"${FF[@]}" "${src_video[@]}" "${src_audio[@]}" -c:v libvpx-vp9 -deadline realtime -cpu-used 8 -c:a libopus -metadata title="WebM Title" video_basic.webm

# 13. Raw HEVC elementary stream.
"${FF[@]}" "${src_video[@]}" -c:v libx265 -x265-params log-level=error -f hevc video_raw.hevc

# 14. WAV (PCM) with INFO and BWF bext.
"${FF[@]}" "${src_audio[@]}" -c:a pcm_s16le -write_bext 1 -metadata title="WAV Title" -metadata artist="WAV Artist" \
  -metadata description="Broadcast description" -metadata originator="Kiroku" -metadata origination_date=2022-03-04 \
  -metadata origination_time=05:06:07 audio_bwf.wav

# 15. HDR-tagged 10-bit HEVC MP4 (PQ / BT.2020).
# The VUI flags go to x265 explicitly; the MP4 muxer writes no 'colr' box, so the SPS VUI is the only signalling.
"${FF[@]}" "${src_video[@]}" -c:v libx265 \
  -x265-params log-level=error:colorprim=bt2020:transfer=smpte2084:colormatrix=bt2020nc:hdr10=1:max-cll=1000,400 \
  -pix_fmt yuv420p10le -tag:v hvc1 -color_primaries bt2020 -color_trc smpte2084 -colorspace bt2020nc video_hdr10.mp4

# 16. Variable frame rate MP4 (frame timestamps 0,1,2,4,6,... via setpts).
"${FF[@]}" -f lavfi -i "testsrc2=size=160x120:rate=30:duration=1" -vf "setpts='if(lt(N,10),N,2*N-10)/(30*TB)'" \
  -fps_mode vfr -c:v libx264 -preset ultrafast video_vfr.mp4

# 17. Mixed streams: two video tracks, two audio tracks, one subtitle track (MOV text).
printf '1\n00:00:00,000 --> 00:00:00,900\nhello\n' > "$TMP/sub.srt"
"${FF[@]}" "${src_video[@]}" -f lavfi -i "testsrc=size=160x120:rate=25:duration=1" "${src_audio[@]}" \
  -f lavfi -i "sine=frequency=880:duration=1" -i "$TMP/sub.srt" \
  -map 0:v -map 1:v -map 2:a -map 3:a -map 4:s -c:v libx264 -preset ultrafast -c:a aac -c:s mov_text \
  -metadata:s:a:0 language=eng -metadata:s:a:1 language=jpn video_mixed_streams.mp4

# 18. MP4 with no timestamps and no device tags at all (absent capture time).
"${FF[@]}" "${src_video[@]}" -c:v libx264 -preset ultrafast -map_metadata -1 "${bitexact[@]}" video_no_timestamps.mp4

# 19. File with a false extension (PNG bytes named .jpg).
cp "$TMP/base.png" false_extension_png.jpg

# 20. Truncated JPEG and corrupt header.
head -c 600 jpeg_full_exif.jpg > truncated.jpg
printf 'NOT A REAL MEDIA FILE\n' > corrupt_header.mp4

# 21. MP3 (VBR, Xing header) with ID3v2.4 tags, and a bare CBR MPEG stream without ID3 or Xing (signature-only
#     detection, estimated duration).
"${FF[@]}" "${src_audio[@]}" -c:a libmp3lame -q:a 4 -id3v2_version 4 -metadata title="MP3 Title" -metadata artist="MP3 Artist" \
  -metadata album="MP3 Album" -metadata date=2021 -metadata comment="MP3 comment" audio_id3v24.mp3
"${FF[@]}" "${src_audio[@]}" -c:a libmp3lame -b:a 128k -write_xing 0 -id3v2_version 0 -fflags +bitexact -f mp3 audio_bare.mp3

echo "Generated fixtures in $OUT"
