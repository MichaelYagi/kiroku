#!/usr/bin/env python3
"""Writes fixtures/manifest.json: source, licence, SHA-256, and independently observed expectations.

Expected values come from ExifTool (and ffprobe for streams), never from Kiroku, so the manifest is an
independent record. Run with:  python3 -I scripts/record-manifest.py
"""
import hashlib, json, os, subprocess, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
FIX = os.path.join(ROOT, "fixtures")
EXIFTOOL = os.environ.get("EXIFTOOL") or os.path.join(ROOT, ".tools", "exiftool-dist", "exiftool")

SOURCES = {
    "media/generated": {
        "source": "Generated by scripts/generate-fixtures.sh (ffmpeg test patterns + ExifTool-written tags)",
        "license": "CC0-1.0",
    },
    "media/exiftool": {
        "source": "ExifTool 13.60 distribution, t/images (https://exiftool.org)",
        "license": "Same terms as Perl (Artistic-1.0-Perl OR GPL-1.0-or-later); test images by Phil Harvey and contributors",
    },
    "external": {
        "source": "raw.pixls.us (downloaded by scripts/fetch-fixtures.sh, not committed)",
        "license": "CC0-1.0",
    },
}

KEYS = [
    "File:FileType", "File:MIMEType", "IFD0:Make", "IFD0:Model", "ExifIFD:LensModel", "ExifIFD:DateTimeOriginal",
    "ExifIFD:OffsetTimeOriginal", "ExifIFD:ISO", "ExifIFD:FNumber", "ExifIFD:ExposureTime", "ExifIFD:FocalLength",
    "IFD0:Orientation", "Composite:ImageSize", "Composite:GPSLatitude", "Composite:GPSLongitude", "Composite:Rotation",
    "Keys:Make", "Keys:Model", "Keys:CreationDate", "QuickTime:Duration", "Composite:LensID",
]

LIMITATIONS = {
    "truncated.jpg": "Deliberately truncated; PARTIAL expected.",
    "corrupt_header.mp4": "Not media; UNSUPPORTED expected.",
    "false_extension_png.jpg": "PNG bytes with .jpg extension; EXTENSION_MISMATCH expected.",
    "mislabeled_jpeg_as.dng": "A JPEG uploaded as .dng on raw.pixls.us; detected as JPEG by signature.",
    "Pentax.avi": "ExifTool test file with media data removed; RIFF size larger than file (PARTIAL).",
    "RIFF.avi": "ExifTool test file with media data removed; RIFF size larger than file (PARTIAL).",
    "RIFF.wav": "ExifTool test file truncated inside a chunk (PARTIAL).",
    "video_hdr10.mp4": "No 'colr' box; HDR signalling only in the HEVC SPS VUI inside hvcC.",
}

def sha256(p):
    h = hashlib.sha256()
    with open(p, "rb") as f:
        for chunk in iter(lambda: f.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()

def exiftool(p):
    if not os.path.exists(EXIFTOOL):
        return {}
    out = subprocess.run([EXIFTOOL, "-j", "-n", "-G1", p], capture_output=True, timeout=120).stdout
    try:
        d = json.loads(out)[0]
    except Exception:
        return {}
    return {k: d[k] for k in KEYS if k in d}

entries = []
for sub, meta in SOURCES.items():
    d = os.path.join(FIX, sub)
    if not os.path.isdir(d):
        continue
    for name in sorted(os.listdir(d)):
        p = os.path.join(d, name)
        if not os.path.isfile(p) or name.endswith(".part"):
            continue
        entries.append({
            "path": f"{sub}/{name}",
            "committed": sub != "external",
            "sizeBytes": os.path.getsize(p),
            "sha256": sha256(p),
            **meta,
            "expected": {"exiftool-13.60": exiftool(p)},
            "knownLimitations": LIMITATIONS.get(name),
        })

manifest = {
    "description": "Kiroku test fixtures. Expected values are independent ExifTool reads, not Kiroku output.",
    "privacy": "No personal photos. GPS values in generated fixtures are landmarks written on purpose.",
    "fixtures": entries,
}
with open(os.path.join(FIX, "manifest.json"), "w", encoding="utf-8") as f:
    json.dump(manifest, f, indent=2, ensure_ascii=False)
    f.write("\n")
print(f"wrote {len(entries)} entries")
